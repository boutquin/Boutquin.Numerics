using Boutquin.Numerics.Statistics;

namespace Boutquin.Numerics.Tests.Verification;

/// <summary>
/// Cross-language verification for <see cref="GarchOneOneEstimator{T}"/>.
/// Compares the C# QMLE fit against an independent scipy Nelder-Mead
/// reference run generated by <c>tests/Verification/generate_garch_vectors.py</c>.
/// </summary>
public sealed class GarchVerificationTests : CrossLanguageVerificationBase
{
    /// <summary>
    /// Fitted parameters (omega, alpha, beta) must agree with the scipy
    /// reference within a generous statistical tolerance (Nelder-Mead from
    /// two independent implementations converging to the same stationary
    /// point of a non-convex likelihood surface).
    /// </summary>
    [Fact]
    public void GarchFit_MatchesScipy_Parameters()
    {
        using var doc = LoadVector("garch");
        var root = doc.RootElement;
        var returns = GetDoubleArray(root.GetProperty("returns"));
        var omegaRef = root.GetProperty("omega_fit").GetDouble();
        var alphaRef = root.GetProperty("alpha_fit").GetDouble();
        var betaRef = root.GetProperty("beta_fit").GetDouble();

        var result = GarchOneOneEstimator<double>.Fit(returns);

        // Independent optimizers may drift, but the positive variance floor must survive.
        AssertScalarWithin(result.Omega, omegaRef, omegaRef * 0.5, "omega");
        AssertScalarWithin(result.Alpha, alphaRef, 0.05, "alpha");
        AssertScalarWithin(result.Beta, betaRef, 0.05, "beta");
    }

    /// <summary>
    /// Filtered conditional variances should agree with the scipy reference
    /// across the entire series, including later volatility clusters.
    /// </summary>
    [Fact]
    public void GarchFit_MatchesScipy_ConditionalVariances()
    {
        using var doc = LoadVector("garch");
        var root = doc.RootElement;
        var returns = GetDoubleArray(root.GetProperty("returns"));
        var hvecRef = GetDoubleArray(root.GetProperty("conditional_variances"));

        var result = GarchOneOneEstimator<double>.Fit(returns);
        var hvec = result.ConditionalVariances;

        Assert.Equal(returns.Length, hvecRef.Length);
        Assert.Equal(hvecRef.Length, hvec.Length);

        // Both optimizers fit the same data, so use the iterative numerical
        // tolerance (1e-6 variance units), not a sampling-error allowance.
        for (var i = 0; i < hvecRef.Length; i++)
        {
            AssertScalarWithin(hvec[i], hvecRef[i], PrecisionNumeric, $"h[{i}]");
        }
    }
}
