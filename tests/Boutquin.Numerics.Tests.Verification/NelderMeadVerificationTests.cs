using Boutquin.Numerics.Solvers;
using FluentAssertions;

namespace Boutquin.Numerics.Tests.Verification;

/// <summary>
/// Cross-language verification tests for <see cref="NelderMeadMinimizer{T}"/>.
/// Reference vectors generated by
/// <c>tests/Verification/generate_nelder_mead_vectors.py</c>
/// using <c>scipy.optimize.minimize(method='Nelder-Mead')</c>.
/// </summary>
public sealed class NelderMeadVerificationTests : CrossLanguageVerificationBase
{
    private static Func<double[], double> ResolveFunction(string name) => name switch
    {
        "rosenbrock" => x => (1.0 - x[0]) * (1.0 - x[0]) + 100.0 * (x[1] - x[0] * x[0]) * (x[1] - x[0] * x[0]),
        "sphere_3d" => x => x[0] * x[0] + x[1] * x[1] + x[2] * x[2],
        "beale" => x =>
        {
            var t1 = 1.5 - x[0] + x[0] * x[1];
            var t2 = 2.25 - x[0] + x[0] * x[1] * x[1];
            var t3 = 2.625 - x[0] + x[0] * x[1] * x[1] * x[1];
            return t1 * t1 + t2 * t2 + t3 * t3;
        }
        ,
        _ => throw new ArgumentOutOfRangeException(nameof(name), name, "Unknown test function."),
    };

    [Fact]
    public void NelderMead_MatchesSciPyReferenceArgmin()
    {
        using var doc = LoadVector("nelder_mead");
        var cases = doc.RootElement.GetProperty("cases");
        Assert.Equal(3, cases.GetArrayLength());
        Assert.Equal(
            ["beale", "rosenbrock", "sphere_3d"],
            cases.EnumerateArray().Select(c => c.GetProperty("name").GetString()!).OrderBy(name => name).ToArray());

        foreach (var c in cases.EnumerateArray())
        {
            var name = c.GetProperty("name").GetString()!;
            var x0 = GetDoubleArray(c.GetProperty("x0"));
            var expectedArgmin = GetDoubleArray(c.GetProperty("argmin"));
            var expectedFmin = c.GetProperty("fmin").GetDouble();
            var precision = c.GetProperty("precision").GetDouble();
            var f = ResolveFunction(name);

            var opts = name == "beale"
                ? new SimplexOptions<double>(MaxIterations: 5000)
                : null;

            var result = NelderMeadMinimizer<double>.Minimize(f, x0, opts);

            result.Converged.Should().BeTrue($"NelderMead must converge for {name}");

            Assert.NotEmpty(expectedArgmin);
            Assert.Equal(x0.Length, expectedArgmin.Length);
            Assert.Equal(expectedArgmin.Length, result.Argmin.Length);

            for (var i = 0; i < expectedArgmin.Length; i++)
            {
                AssertScalarWithin(
                    result.Argmin[i],
                    expectedArgmin[i],
                    precision,
                    $"NelderMead/{name} argmin[{i}]");
            }

            AssertScalarWithin(
                result.MinValue,
                expectedFmin,
                precision * precision + PrecisionStatistical,
                $"NelderMead/{name} fmin");
        }
    }
}
