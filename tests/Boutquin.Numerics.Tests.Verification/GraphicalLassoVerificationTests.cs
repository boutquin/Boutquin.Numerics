using Boutquin.Numerics.Statistics;

namespace Boutquin.Numerics.Tests.Verification;

/// <summary>
/// Cross-language verification tests for <see cref="GraphicalLassoSolver{T}"/>.
/// Compares the C# BCD implementation against scikit-learn's GraphicalLasso
/// reference vectors generated by <c>tests/Verification/generate_graphical_lasso_vectors.py</c>.
/// </summary>
public sealed class GraphicalLassoVerificationTests : CrossLanguageVerificationBase
{
    // Retain the existing comparison tolerance; both implementations receive the same S.
    private const double LargeLambdaDiagonalTolerance = 0.03;

    // ─────────────────────────────────────────────────────────────────────────
    //  3×3 sparse precision model
    // ─────────────────────────────────────────────────────────────────────────

    /// <summary>
    /// Compare against sklearn's off-diagonal-penalty solver applied to S + λI,
    /// which is equivalent to the all-entry penalty because positive-definite
    /// precision matrices have positive diagonal entries. BIC evaluates the
    /// original sample covariance S, using the independently generated grid scores.
    /// </summary>
    [Fact]
    public void GraphicalLasso_3x3Sparse_BicSelectsSklearnLambda_MatchesSklearn()
    {
        using var doc = LoadVector("graphical_lasso");
        var case3 = doc.RootElement.GetProperty("case_3x3_sparse");

        var sampleCov = GetDouble2D(case3.GetProperty("sample_covariance"));
        var sklearnPrecision = GetDouble2D(case3.GetProperty("sklearn_precision"));
        var sklearnLambda = case3.GetProperty("lambda").GetDouble();   // 0.05
        var nSamples = case3.GetProperty("n_samples").GetInt32();      // 500

        var lambdaGrid = case3.GetProperty("bic_grid").EnumerateArray().Select(x => x.GetDouble()).ToArray();
        var result = GraphicalLassoSolver<double>.SolveWithBic(
            sampleCov, nSamples, lambdaGrid,
            new GraphicalLassoOptions<double>(MaxIterations: 500, Tolerance: 1e-8));

        // The oracle computes each BIC score against the original, unshifted S.
        Assert.Equal(case3.GetProperty("bic_selected_lambda").GetDouble(), result.Lambda);
        Assert.Equal(sklearnLambda, result.Lambda);

        // Retain the existing numerical tolerance for this cross-library comparison.
        AssertMatrixWithin(result.Precision, sklearnPrecision,
            tolerance: 0.05, "precision_3x3_bic_selected");
    }

    /// <summary>
    /// The sparsity pattern should match: zero entries in sklearn's precision
    /// should also be near zero in the C# solution.
    /// </summary>
    [Fact]
    public void GraphicalLasso_3x3Sparse_ZeroEntriesMatchSklearn()
    {
        using var doc = LoadVector("graphical_lasso");
        var case3 = doc.RootElement.GetProperty("case_3x3_sparse");

        var sampleCov = GetDouble2D(case3.GetProperty("sample_covariance"));
        var sklearnPrecision = GetDouble2D(case3.GetProperty("sklearn_precision"));
        var lambda = case3.GetProperty("lambda").GetDouble();

        var result = GraphicalLassoSolver<double>.Solve(
            sampleCov, lambda,
            new GraphicalLassoOptions<double>(MaxIterations: 500, Tolerance: 1e-8));

        var p = sklearnPrecision.GetLength(0);
        for (var i = 0; i < p; i++)
        {
            for (var j = 0; j < p; j++)
            {
                if (i == j)
                {
                    continue;
                }

                var sklearnEntry = sklearnPrecision[i, j];
                var csharpEntry = result.Precision[i, j];

                // Keep the zero-edge threshold close to sklearn's 1e-4 classification.
                if (Math.Abs(sklearnEntry) < 1e-4)
                {
                    Assert.True(Math.Abs(csharpEntry) < 1e-3,
                        $"theta[{i},{j}] is near-zero in sklearn ({sklearnEntry:G4}), " +
                        $"but C# gave {csharpEntry:G4}");
                }
            }
        }
    }

    // ─────────────────────────────────────────────────────────────────────────
    //  5×5 block-diagonal model
    // ─────────────────────────────────────────────────────────────────────────

    /// <summary>
    /// The C# and sklearn precision matrices agree on the 5×5 block-diagonal model.
    /// </summary>
    [Fact]
    public void GraphicalLasso_5x5BlockDiagonal_MatchesSklearn()
    {
        using var doc = LoadVector("graphical_lasso");
        var case5 = doc.RootElement.GetProperty("case_5x5_block_diagonal");

        var sampleCov = GetDouble2D(case5.GetProperty("sample_covariance"));
        var sklearnPrecision = GetDouble2D(case5.GetProperty("sklearn_precision"));
        var lambda = case5.GetProperty("lambda").GetDouble();

        var result = GraphicalLassoSolver<double>.Solve(
            sampleCov, lambda,
            new GraphicalLassoOptions<double>(MaxIterations: 500, Tolerance: 1e-8));

        var precision = result.Precision;
        AssertScalarWithin(precision[2, 3], sklearnPrecision[2, 3],
            0.04, "block_2_theta[2,3]");
        AssertScalarWithin(precision[3, 4], sklearnPrecision[3, 4],
            0.04, "block_2_theta[3,4]");
        AssertMatrixWithin(precision, sklearnPrecision,
            tolerance: 0.04, "precision_5x5_block_diag");
    }

    /// <summary>
    /// For the 5×5 block model the cross-block precision entries should be near zero.
    /// </summary>
    [Fact]
    public void GraphicalLasso_5x5BlockDiagonal_CrossBlockEntriesNearZero()
    {
        using var doc = LoadVector("graphical_lasso");
        var case5 = doc.RootElement.GetProperty("case_5x5_block_diagonal");

        var sampleCov = GetDouble2D(case5.GetProperty("sample_covariance"));
        var lambda = case5.GetProperty("lambda").GetDouble();

        var result = GraphicalLassoSolver<double>.Solve(
            sampleCov, lambda,
            new GraphicalLassoOptions<double>(MaxIterations: 500, Tolerance: 1e-8));

        // Cross-block entries: rows {0,1} × cols {2,3,4} and vice versa
        (int Row, int Col)[] crossPairs =
        [
            (0, 2), (0, 3), (0, 4),
            (1, 2), (1, 3), (1, 4),
        ];

        foreach (var (i, j) in crossPairs)
        {
            Assert.True(Math.Abs(result.Precision[i, j]) < 0.5,
                $"cross-block theta[{i},{j}] = {result.Precision[i, j]:G4} should be near zero");
            Assert.True(Math.Abs(result.Precision[j, i]) < 0.5,
                $"cross-block theta[{j},{i}] = {result.Precision[j, i]:G4} should be near zero");
        }
    }

    // ─────────────────────────────────────────────────────────────────────────
    //  Large λ → diagonal
    // ─────────────────────────────────────────────────────────────────────────

    [Fact]
    public void GraphicalLasso_LargeLambda_OracleRejectsCorruptedDiagonal()
    {
        using var doc = LoadVector("graphical_lasso");
        var caseL = doc.RootElement.GetProperty("case_3x3_large_lambda");
        var sklearnPrecision = GetDouble2D(caseL.GetProperty("sklearn_precision"));

        Assert.ThrowsAny<Xunit.Sdk.XunitException>(() =>
            AssertScalarWithin(sklearnPrecision[0, 0] + 0.49, sklearnPrecision[0, 0],
                LargeLambdaDiagonalTolerance, "corrupted_diagonal_theta[0,0]"));
    }

    /// <summary>
    /// At very large λ the C# solution should produce approximately diagonal precision,
    /// consistent with the sklearn reference.
    /// </summary>
    [Fact]
    public void GraphicalLasso_LargeLambda_SklearnAgrees()
    {
        using var doc = LoadVector("graphical_lasso");
        var caseL = doc.RootElement.GetProperty("case_3x3_large_lambda");

        var sampleCov = GetDouble2D(caseL.GetProperty("sample_covariance"));
        var sklearnPrecision = GetDouble2D(caseL.GetProperty("sklearn_precision"));
        var lambda = caseL.GetProperty("lambda").GetDouble();

        var result = GraphicalLassoSolver<double>.Solve(
            sampleCov, lambda,
            new GraphicalLassoOptions<double>(MaxIterations: 500, Tolerance: 1e-8));

        var p = sklearnPrecision.GetLength(0);

        // Diagonal should approximately match sklearn
        for (var i = 0; i < p; i++)
        {
            AssertScalarWithin(result.Precision[i, i], sklearnPrecision[i, i],
                tolerance: LargeLambdaDiagonalTolerance, label: $"diagonal_theta[{i},{i}]");
            AssertScalarWithin(result.Precision[i, i], 1.0 / (sampleCov[i, i] + lambda),
                tolerance: 1e-8, label: $"analytic_diagonal_theta[{i},{i}]");
        }

        // Off-diagonal should be near zero (both sklearn and C#)
        for (var i = 0; i < p; i++)
        {
            for (var j = 0; j < p; j++)
            {
                if (i != j)
                {
                    Assert.True(Math.Abs(result.Precision[i, j]) < 1e-4,
                        $"off-diagonal theta[{i},{j}] = {result.Precision[i, j]:G4} should be ~0 at large lambda");
                }
            }
        }
    }
}
